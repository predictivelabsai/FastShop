"""Regenerate static/admin/icons.js from the Lucide SVGs in static/admin/icons.

Run after adding or removing an icon file:  python scripts/build_admin_icons.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "static" / "admin" / "icons"


def inner(svg: str) -> str:
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    return re.sub(r"\s+", " ", body).replace("> <", "><").strip()


def main() -> None:
    icons = {path.stem: inner(path.read_text()) for path in sorted(ICONS.glob("*.svg"))}
    source = ("/* Generated by scripts/build_admin_icons.py from Lucide (ISC licence). Do not edit. */\n"
              "window.FS_ICONS = " + json.dumps(icons, indent=0, sort_keys=True) + ";\n"
              "window.fsIcon = (name, size = 18) => '<svg viewBox=\"0 0 24 24\" width=\"' + size + "
              "'\" height=\"' + size + '\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\" "
              "stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\" focusable=\"false\" "
              "class=\"fs-icon\">' + (window.FS_ICONS[name] || '') + '</svg>';\n")
    (ROOT / "static" / "admin" / "icons.js").write_text(source)


if __name__ == "__main__":
    main()
